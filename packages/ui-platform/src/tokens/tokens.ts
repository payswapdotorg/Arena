/**
 * Turn token entries into a `:root { … }` CSS custom-properties block.
 * Duplicate variable names are rejected — two tokens may never own the
 * same CSS variable.
 */
export function cssVariablesFromEntries(
  entries: readonly TokenEntry[],
): string {
  const seen = new Set<string>();
  const lines: string[] = [];
  for (const entry of entries) {
    if (seen.has(entry.variable)) {
      throw new Error(
        `duplicate CSS variable in token registry: ${entry.variable}`,
      );
    }
    seen.add(entry.variable);
    lines.push(`  ${entry.variable}: ${entry.value};`);
  }
  return lines.join('\n');
}

/** Deterministically regenerate the full tokens stylesheet. */
export function generateTokensCss(): string {
  const groupOrder = new Map<string, number>(
    TOKEN_GROUPS.map((group, index) => [group, index]),
  );
  const sorted = [...TOKEN_ENTRIES].sort((a, b) => {
    const groupDelta =
      (groupOrder.get(a.group) ?? TOKEN_GROUPS.length) -
      (groupOrder.get(b.group) ?? TOKEN_GROUPS.length);
    if (groupDelta !== 0) return groupDelta;
    return a.variable < b.variable ? -1 : a.variable > b.variable ? 1 : 0;
  });
  return [
    '/*',
    ' * Arena design tokens — GENERATED FILE, do not edit by hand.',
    ` * Generated by @arena/ui-platform generateTokensCss() (tokens v${TOKENS_VERSION}).`,
    ' * Regenerate with: pnpm --filter @arena/ui-platform tokens:css',
    ' * Drift is caught by src/tokens/tokens.test.ts.',
    ' */',
    '',
    ':root {',
    cssVariablesFromEntries(sorted),
    '}',
    '',
  ].join('\n');
}
