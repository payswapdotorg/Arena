/**
 * Fail-closed lookup of one state kind's treatment. Unknown kinds throw —
 * the vocabulary is closed on purpose (the UI must never invent an
 * eleventh kind of truth).
 */
export function stateKindConfig(kind: string): StateKindConfig {
  const config = (STATE_KIND_CONFIGS as Record<string, StateKindConfig | undefined>)[
    kind
  ];
  if (config === undefined) {
    throw new Error(
      `unknown product-truth state kind: ${JSON.stringify(kind)} (allowed: ${STATE_KINDS.join(', ')})`,
    );
  }
  return config;
}

