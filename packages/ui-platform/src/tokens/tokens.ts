/** The visual + semantic treatment of one product-truth state kind. */
export interface StateKindConfig {
  readonly kind: StateKind;
  /** Human-facing badge label (always rendered — meaning never rests on color alone). */
  readonly label: string;
  /** Strong color: badge text and marker on the soft tint. */
  readonly color: string;
  /** Soft tint: badge background. */
  readonly softColor: string;
  /** Distinct marker shape (color-independent redundancy). */
  readonly marker: StateMarkerShape;
  /** One-line product-truth meaning, used for tooltips/teaching UI. */
  readonly meaning: string;
}

