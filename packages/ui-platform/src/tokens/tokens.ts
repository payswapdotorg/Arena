/** camelCase -> kebab-case (CSS custom properties are case-sensitive). */
function kebab(key: string): string {
  return key.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

function scale(
  group: TokenGroup,
  prefix: CssVariableName,
  values: Readonly<Record<string, string>>,
  description: string,
): TokenEntry[] {
  return Object.entries(values).map(([key, value]) => ({
    variable: `${prefix}-${kebab(key)}` as CssVariableName,
    value,
    group,
    description,
  }));
}

function truthEntries(): TokenEntry[] {
  const entries: TokenEntry[] = [];
  for (const kind of STATE_KINDS) {
    const config = stateKindConfig(kind);
    entries.push({
      variable: `--arena-truth-${kind}-color` as CssVariableName,
      value: config.color,
      group: 'truth',
      description: `${config.label} — strong color`,
    });
    entries.push({
      variable: `--arena-truth-${kind}-soft` as CssVariableName,
      value: config.softColor,
      group: 'truth',
      description: `${config.label} — soft tint`,
    });
  }
  return entries;
}

